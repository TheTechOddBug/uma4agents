#!/usr/bin/env node
/**
 * Generates everything that has to agree with the palette:
 *
 *   src/style/theme.generated.css   the CSS custom properties
 *   static/brand/u4a-mark.svg       1b, the U4A monogram
 *   static/brand/uma4-disc.svg      1a, the UMA disc
 *
 * from src/style/theme.js (colour) and src/style/marks.js (geometry).
 *
 * The stylesheets need the palette as custom properties, the app needs it as
 * JavaScript, and the brand assets need it baked in — generating all three
 * from one source is what keeps them from drifting. Before this, the same hex
 * codes were maintained by hand in variables.sass, stage.css and story.js.
 *
 * Runs from `prebuild` / `predevelop`, so nothing has to be run by hand.
 */
const fs = require("fs");
const path = require("path");
const { toCss, role } = require("../src/style/theme.js");
const { monogram, disc } = require("../src/style/marks.js");

const root = path.join(__dirname, "..");
const rel = (p) => path.relative(process.cwd(), p);
const written = [];

function write(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents, "utf8");
  written.push(rel(file));
}

// --- the custom properties ----------------------------------------------
write(
  path.join(root, "src", "style", "theme.generated.css"),
  `/* GENERATED by scripts/gen-theme.js — do not edit.
 * Change the palette in src/style/theme.js instead. */\n\n` + toCss()
);

// --- the brand marks -----------------------------------------------------
const note = (name, what) =>
  `<!-- ${name} — GENERATED by scripts/gen-theme.js. Do not edit.
     Colour: src/style/theme.js · Geometry: src/style/marks.js
     ${what} -->`;

const f = monogram.frame;
write(
  path.join(root, "static", "brand", "u4a-mark.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${monogram.viewBox}" width="256" height="256" fill="none">
  ${note("U4A monogram (1b)", "Transparent outside the chip; the chip carries its own dark ground so the mark reads on any background.")}
  <title>U4A</title>
  <rect x="${f.x}" y="${f.y}" width="${f.w}" height="${f.h}" rx="${f.rx}" fill="${role.bg}" stroke="${role.accent}" stroke-width="${monogram.frameWidth}"/>
  <g stroke-width="${monogram.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">
    <path d="${monogram.u}" stroke="${role.ink}"/>
    <path d="${monogram.four}" stroke="${role.primary}"/>
    <path d="${monogram.a}" stroke="${role.ink}"/>
  </g>
  <path d="${monogram.bar}" stroke="${role.accent}" stroke-width="${monogram.barWidth}" stroke-linecap="round"/>
</svg>
`
);

// The favicon is the monogram. The chip carries its own ground, so it reads
// against a light browser tab as well as a dark one.
write(
  path.join(root, "static", "favicon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${monogram.viewBox}" fill="none">
  ${note("Favicon — the U4A monogram", "Same geometry as static/brand/u4a-mark.svg.")}
  <rect x="${f.x}" y="${f.y}" width="${f.w}" height="${f.h}" rx="${f.rx}" fill="${role.bg}" stroke="${role.accent}" stroke-width="${monogram.frameWidth}"/>
  <g stroke-width="${monogram.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">
    <path d="${monogram.u}" stroke="${role.ink}"/>
    <path d="${monogram.four}" stroke="${role.primary}"/>
    <path d="${monogram.a}" stroke="${role.ink}"/>
  </g>
  <path d="${monogram.bar}" stroke="${role.accent}" stroke-width="${monogram.barWidth}" stroke-linecap="round"/>
</svg>
`
);

write(
  path.join(root, "static", "brand", "uma4-disc.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${disc.viewBox}" width="256" height="256" fill="none">
  ${note("UMA disc (1a)", "Transparent outside the disc; the off-white face is part of the mark, so it sits on a dark or a light page.")}
  <title>UMA4Agents</title>
  <circle cx="${disc.face.cx}" cy="${disc.face.cy}" r="${disc.face.r}" fill="${role.paper}"/>
  <circle cx="${disc.ring.cx}" cy="${disc.ring.cy}" r="${disc.ring.r}" stroke="${role.accent}" stroke-width="${disc.ringWidth}"/>
  <path d="${disc.four}" stroke="${role.primary}" stroke-width="${disc.fourWidth}" stroke-linecap="round" stroke-linejoin="round"/>
  <g stroke="${role.bg}" stroke-width="${disc.strokeWidth}" stroke-linecap="round" stroke-linejoin="round">
    <path d="${disc.u}"/>
    <path d="${disc.m}"/>
    <path d="${disc.a}"/>
  </g>
</svg>
`
);

console.log("generated:\n  " + written.join("\n  "));
